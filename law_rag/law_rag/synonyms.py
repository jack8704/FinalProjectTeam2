def expand_query(q: str, synonyms: dict = SYNONYMS) -> str:
    """질문에 사전 단어가 있으면 법령 용어를 뒤에 덧붙임 (원 질문은 그대로 유지)"""
    import re

    q = re.sub(r"(\d+)\s*(m|M|미터)\b", r"\1미터", q)  # "10m" → "10미터" (법령 표기)
    compact = q.replace(" ", "")
    words = []
    for k, v in synonyms.items():
        if k in compact:
            words += [
                w for w in v.split() if w not in words
            ]  # 같은 법령 용어가 여러 번 붙어 점수가 쏠리는 것 방지
    return f"{q} {' '.join(words)}" if words else q
