    scores = {}
    for cat, kws in CATEGORY_KEYWORDS.items():
        s = sum(
            compact.count(kw.replace(" ", "")) * w for kw, w in kws.items()
        )  # 띄어쓰기 차이 무시
        if s >= min_score:
            scores[cat] = s
    return [c for c, _ in sorted(scores.items(), key=lambda x: -x[1])][:top_k]
